// Emits sd-signs/shared/glyphs.lua from the metrics measured off the real meshes,
// so in-game sign layout matches the models instead of guessing advance widths.
const fs = require('fs');
const path = require('path');

// Resolved from this file's own location, like the Blender half of the toolchain, so a
// clone runs without editing paths. This script sits at sd-signs/assets/blender, which
// puts the metrics beside it and shared/ two levels up.
const SRC = path.join(__dirname, 'glyph_metrics.json');
const DST = path.join(__dirname, '..', '..', 'shared', 'glyphs.lua');

const m = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const L = [];
const p = (s) => L.push(s);

p('-- GENERATED by assets/alphabet3d/gen_glyphs_lua.js -- do not hand-edit.');
p('-- Metrics are measured off the actual exported meshes, so sign layout in game');
p('-- matches the props exactly rather than guessing at advance widths.');
p('');
p('local Glyphs = {}');
p('');
p('--- Cap height of the source models, in metres. Sign scale 1.0 == 1 m capitals.');
p('Glyphs.CAP = ' + m.cap);
p('--- Front-to-back depth of the source models, in metres (bevel skirt not included).');
p('Glyphs.DEPTH = ' + m.depth);
p('--- Bevel radius in metres: adds this beyond DEPTH, and above/below the cap line.');
p('Glyphs.BEVEL = ' + m.bevel);
p('--- Default gap between letters, in cap-height units.');
p('Glyphs.TRACKING = ' + m.tracking);
p('--- Advance width of a space character, in cap-height units.');
p('Glyphs.SPACE = ' + m.space);
p('');
p('--- Palette colour names. The index into this list IS the model\'s tint index, so');
p('--- the order here must match the row order of textures/alphabet_tint.dds.');
p('Glyphs.COLOURS = { ' + m.palette.map((c) => "'" + c + "'").join(', ') + ' }');
p('');
p('--- Colour name -> tint index (0-based, unlike COLOURS which is a Lua 1-based list).');
p('Glyphs.TINT = {');
m.palette.forEach((c, i) => p("    ['" + c + "'] = " + i + ','));
p('}');
p('');
p('--- char -> { model = streamed model name (only the finish tag is appended),');
p('---           w = advance width, top/bot = extent above/below the baseline }');
p('--- All measurements are in cap-height units, so they scale with the sign.');
p('--- Keys are raw UTF-8 byte strings, so multi-byte symbols must be looked up by');
p('--- whole character -- see the utf8-aware iteration in shared/sign.lua.');
p('Glyphs.META = {');

// Only ' and \ need escaping inside a Lua single-quoted string; UTF-8 bytes are
// literal. Both characters are in the symbol set, so this is not hypothetical.
const luaKey = (c) => c.replace(/\\/g, '\\\\').replace(/'/g, "\\'");

for (const g of m.glyphs) {
  p(
    "    ['" + luaKey(g.ch) + "'] = { model = '" + g.model + "', w = " + g.w +
    ', top = ' + g.top + ', bot = ' + g.bot + ' },'
  );
}
p('}');
p('');
p('--- Available finishes. "painted" is matte (default_tnt.sps); "neon" lights the');
p('--- letter face with emissive_tnt.sps so it glows at night.');
p("Glyphs.STYLES = { 'painted', 'neon' }");
p('');
p('--- Resolve the streamed model name for a character.');
p('--- Returns nil for characters the alphabet does not cover (so callers can skip them).');
p('---');
p('--- Colour is deliberately absent. Both finishes carry a tint palette, so a colour');
p('--- is chosen per entity with SetObjectTextureVariation(ent, Glyphs.tint(colour))');
p('--- rather than by picking a different model -- 382 models instead of 3820.');
p('---@param char string single character');
p('---@param style string|nil "painted" (default) or "neon"');
p('---@return string|nil');
p('function Glyphs.model(char, style)');
p('    local meta = Glyphs.META[char]');
p('    if not meta then return nil end');
p("    return meta.model .. (style == 'neon' and '_neon' or '')");
p('end');
p('');
p('--- Palette colour name -> tint index, the value the game wants.');
p('---@param colour string');
p('---@return integer tint index, 0 (white) when the name is unknown');
p('function Glyphs.tint(colour)');
p('    return Glyphs.TINT[colour] or 0');
p('end');
p('');
p('--- Iterate `text` one whole character at a time, UTF-8 aware.');
p('--- Byte-wise iteration would never match a multi-byte symbol key and would');
p('--- silently strip every non-ASCII glyph.');
p('---@param text string');
p('---@return fun(): string|nil');
p('function Glyphs.chars(text)');
p('    local pos = 1');
p('    return function()');
p('        if pos > #text then return nil end');
p('        local nextPos = utf8.offset(text, 2, pos) or (#text + 1)');
p('        local c = text:sub(pos, nextPos - 1)');
p('        pos = nextPos');
p('        return c');
p('    end');
p('end');
p('');
p('return Glyphs');

fs.writeFileSync(DST, L.join('\n') + '\n');
console.log('wrote ' + DST + ' (' + m.glyphs.length + ' glyphs)');
